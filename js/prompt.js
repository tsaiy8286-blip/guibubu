var PROMPT_BLANK = '＿＿＿＿＿＿＿＿＿＿';

// 爻題：陽稱九、陰稱六；初爻、上爻把位置放前面（初九、上六），其他放後面（九二、六五）
function yaoTitle(index, yang) {
  var num = yang ? '九' : '六';
  if (index === 0) return '初' + num;
  if (index === 5) return '上' + num;
  return num + '二三四五'.charAt(index - 1);
}

function guaLine(g) {
  return '第' + g.number + '卦 ' + g.fullName + '（上' + g.upper + '下' + g.lower + '）——' + g.judgment;
}

// 產生貼給 AI 的解卦提示詞：原文＋自動填好的「我的問卦資料」
function toPrompt(info, result) {
  var question = info.question.replace(/\s*\n\s*/g, ' ');
  var moving = result.moving.length
    ? result.moving.map(function (i) {
        return POSITIONS[i] + '（' + yaoTitle(i, result.lines[i].yang) + '）';
      }).join('、')
    : '無（六爻安靜）';

  return PROMPT_HEAD + [
    '# 我的問卦資料',
    '',
    '【問卦問題】：',
    '（' + info.category + '）' + question,
    '',
    '【事情背景】：',
    PROMPT_BLANK,
    '',
    '【我現在最在意／最害怕的事情】：',
    PROMPT_BLANK,
    '',
    '【本卦】：',
    guaLine(result.primary),
    '',
    '【動爻】：',
    moving,
    '',
    '【變卦】：',
    result.changed ? guaLine(result.changed) : '無',
    '',
    PROMPT_TAIL
  ].join('\n');
}

